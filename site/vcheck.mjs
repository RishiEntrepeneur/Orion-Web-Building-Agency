import { chromium } from "playwright";
const b = await chromium.launch({ executablePath:"/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const p = await (await b.newContext({viewport:{width:1440,height:900}})).newPage();
const errs=[]; p.on("pageerror",e=>errs.push(String(e).slice(0,160)));
await p.goto("http://localhost:8812/",{waitUntil:"load"});
await p.waitForTimeout(1600);
console.log("desktop overflow:", await p.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth?"YES":"none"));
console.log("prices:", await p.evaluate(()=>[...document.querySelectorAll(".price .amt")].map(e=>e.textContent.trim()).join(" | ")));
await p.evaluate(()=>document.querySelector("#price").scrollIntoView());
await p.waitForTimeout(900);
await p.screenshot({path:"/home/user/Video-Games/p1.png"});
await p.evaluate(()=>{const f=document.getElementById("brief");f.name.value="Test";f.email.value="a@b.co";f.brief.value="A site";});
await p.evaluate(()=>document.getElementById("brief").requestSubmit());
await p.waitForTimeout(2500);
console.log("note after submit:", (await p.textContent("#formnote")).slice(0,70));
const m = await b.newContext({viewport:{width:390,height:844},isMobile:true});
const mp = await m.newPage(); await mp.goto("http://localhost:8812/",{waitUntil:"load"}); await mp.waitForTimeout(1200);
console.log("mobile overflow:", await mp.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth?"YES":"none"));
console.log("errors:", errs.length?errs:"(none)");
await b.close();
